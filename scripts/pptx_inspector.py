#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
pptx_inspector.py — AI Clean Master PPTX 病灶扫描与配对背景框检测器

扫描 .pptx 文件，识别：
1. 顶部/卡片伪英文与八股眉题小字 (kicker_badge)
2. 卡片内同义反复的凑数解释小字 (redundant_subtext)
3. 页脚/底栏的假大空总结与免责废话 (footer_slop)
4. 伪造的装饰性微数据/角标与符号噪音 (fake_metric / emoji_slop)
5. 小字背后的配对装饰色块 (paired_bg_shape_id，如胶囊框、底栏横条)
6. 正文中的 AI 黑话与八股词条 (buzzwords)
"""

import argparse
import json
import re
import sys
from pathlib import Path
from pptx import Presentation

# 中英文 AI 高频黑话词库
AI_BUZZWORDS = [
    "赋能", "抓手", "闭环", "全链路", "多维度", "全方位", "深层次",
    "底层逻辑", "顶层设计", "范式转移", "生态体系", "协同共振", "组合拳",
    "颗粒度", "痛点剖析", "破局之道", "矩阵", "价值跃迁", "新生态",
    "战略支点", "多维感知", "深度融合", "全渠道", "靶向发力", "精准施策",
    "delve", "testament", "tapestry", "paradigm shift", "synergy", "holistic",
    "empowering", "game-changer", "cutting-edge", "seamless", "leverage"
]

# 伪英文/八股眉题特征正则
KICKER_PATTERNS = [
    re.compile(r"^(SECTION|PART|CHAPTER|MODULE|PHASE|STEP|STAGE)\s*0?\d+", re.I),
    re.compile(r"\b(CORE INSIGHT|STRATEGIC OVERVIEW|KEY TAKEAWAY|AI-POWERED|NEXT-GEN|SYSTEM ONLINE|EXECUTIVE SUMMARY|OVERVIEW)\b", re.I),
    re.compile(r"^(0?\d+\s*[/|·•—-]\s*[A-Z0-9\s_-]{3,})$"),
    re.compile(r"^(核心赋能|战略顶层|多维价值|创新驱动|痛点剖析|破局之道|顶层设计|生态闭环|核心洞察)[\u4e00-\u9fa5]{0,4}$"),
]

# 页脚假大空总结与免责废话正则
FOOTER_PATTERNS = [
    re.compile(r"(本页核心洞察|本页小结|核心结论|核心启示|Takeaway|Key Insight)\s*[:：]", re.I),
    re.compile(r"(仅供参考|仅供演示|具体以实际为准|Generated by AI|AI 生成|内部交流参考)", re.I),
]

# 伪微数据/角标正则
FAKE_METRIC_PATTERNS = [
    re.compile(r"^([+-]?\d{1,3}(\.\d+)?%\s*(EFFICIENCY|UPTIME|ACCURACY|GROWTH|BOOST|提升|赋能)?)$", re.I),
    re.compile(r"^(INDEX|DATA|METRIC|SCORE|STATUS)\s*[:：//]\s*[A-Z0-9.+%-]+$", re.I),
]

EMOJI_SLOP_RE = re.compile(r"[✨🚀💡⚡🔥🎯🌐💎]")


def emu_to_inch(emu_val):
    if emu_val is None:
        return 0.0
    return round(float(emu_val) / 914400.0, 3)


def get_effective_font_pt(paragraph, shape_default_pt=None):
    """获取段落有效字号（pt）"""
    if paragraph.font and paragraph.font.size:
        return round(paragraph.font.size.pt, 1)
    for run in paragraph.runs:
        if run.font and run.font.size:
            return round(run.font.size.pt, 1)
    return shape_default_pt or 14.0


def iter_shapes_recursive(shapes, parent_group_id=None):
    """递归遍历幻灯片中的所有形状（含组合图形内部）"""
    for sp in shapes:
        yield sp, parent_group_id
        if sp.shape_type == 6 and hasattr(sp, "shapes"):  # GROUP
            yield from iter_shapes_recursive(sp.shapes, parent_group_id=sp.shape_id)


def calc_ioa(text_bbox, bg_bbox):
    """计算文本框被候选背景框包含的面积比例 Intersection over Text Area"""
    tx1, ty1, tx2, ty2 = text_bbox
    bx1, by1, bx2, by2 = bg_bbox
    ix1, iy1 = max(tx1, bx1), max(ty1, by1)
    ix2, iy2 = min(tx2, bx2), min(ty2, by2)
    if ix2 <= ix1 or iy2 <= iy1:
        return 0.0
    inter_area = (ix2 - ix1) * (iy2 - iy1)
    text_area = max((tx2 - tx1) * (ty2 - ty1), 1e-6)
    return inter_area / text_area


def detect_buzzwords(text):
    return [w for w in AI_BUZZWORDS if w in text]


def classify_text_issue(text, font_pt, top_ratio, para_index, total_paras):
    """判定单段或单框文本属于哪类 AI 味病灶"""
    clean = text.strip()
    if not clean:
        return []

    issues = []
    # 1. 伪英文/八股眉题胶囊
    for pat in KICKER_PATTERNS:
        if pat.search(clean) and (font_pt <= 15.0 or len(clean) <= 36):
            issues.append("kicker_badge")
            break

    # 2. 页脚/底栏废话或免责
    for pat in FOOTER_PATTERNS:
        if pat.search(clean) or (top_ratio >= 0.82 and font_pt <= 13.0 and any(w in clean for w in ["洞察", "闭环", "赋能", "参考", "抓手"])):
            issues.append("footer_slop")
            break

    # 3. 伪微数据/角标
    for pat in FAKE_METRIC_PATTERNS:
        if pat.search(clean) and len(clean) <= 28:
            issues.append("fake_metric")
            break

    # 4. Emoji 噪音
    if EMOJI_SLOP_RE.search(clean):
        issues.append("emoji_slop")

    # 5. 卡片内凑数解释小字：多段落中的副段落，字号偏小且含典型套话
    if para_index > 0 and total_paras >= 2 and font_pt <= 13.0:
        if any(k in clean for k in ["通过", "实现", "助力", "构建", "赋能", "多维", "闭环", "有效", "体系", "全链路"]):
            issues.append("redundant_subtext")
    elif total_paras == 1 and font_pt <= 11.5 and 0.18 < top_ratio < 0.82:
        if any(k in clean for k in ["通过", "实现", "助力", "构建", "赋能", "多维", "闭环"]):
            issues.append("redundant_subtext")

    return list(dict.fromkeys(issues))


def inspect_pptx(pptx_path: str) -> dict:
    prs = Presentation(pptx_path)
    slide_w = emu_to_inch(prs.slide_width)
    slide_h = emu_to_inch(prs.slide_height)

    report = {
        "file": str(Path(pptx_path).resolve()),
        "slide_width_inch": slide_w,
        "slide_height_inch": slide_h,
        "slide_count": len(prs.slides),
        "slides": [],
        "summary": {
            "total_flagged_shapes": 0,
            "total_paired_bg_shapes": 0,
            "total_buzzword_hits": 0,
        },
    }

    for idx, slide in enumerate(prs.slides, start=1):
        all_shapes = list(iter_shapes_recursive(slide.shapes))
        geom_candidates = []
        text_items = []

        for sp, group_id in all_shapes:
            x1 = emu_to_inch(sp.left)
            y1 = emu_to_inch(sp.top)
            w = emu_to_inch(sp.width)
            h = emu_to_inch(sp.height)
            bbox = (x1, y1, round(x1 + w, 3), round(y1 + h, 3))

            has_nonempty_text = getattr(sp, "has_text_frame", False) and bool(sp.text_frame.text.strip())
            if not has_nonempty_text and sp.shape_type != 6:
                geom_candidates.append({
                    "shape_id": sp.shape_id,
                    "name": sp.name,
                    "bbox": bbox,
                    "width": w,
                    "height": h,
                })

            if has_nonempty_text:
                paras_info = []
                shape_issues = set()
                shape_buzzwords = set()
                top_ratio = (y1 / slide_h) if slide_h > 0 else 0.0
                non_empty_paras = [p for p in sp.text_frame.paragraphs if p.text.strip()]
                total_p = len(non_empty_paras)

                for p_i, p in enumerate(sp.text_frame.paragraphs):
                    p_text = p.text.strip()
                    if not p_text:
                        continue
                    pt = get_effective_font_pt(p)
                    p_issues = classify_text_issue(p_text, pt, top_ratio, p_i, total_p)
                    b_words = detect_buzzwords(p_text)
                    shape_issues.update(p_issues)
                    shape_buzzwords.update(b_words)
                    paras_info.append({
                        "paragraph_index": p_i,
                        "text": p_text,
                        "font_pt": pt,
                        "issues": p_issues,
                        "buzzwords": b_words,
                    })

                text_items.append({
                    "shape_id": sp.shape_id,
                    "name": sp.name,
                    "group_id": group_id,
                    "bbox": list(bbox),
                    "width": w,
                    "height": h,
                    "top_ratio": round(top_ratio, 3),
                    "paragraphs": paras_info,
                    "issues": sorted(shape_issues),
                    "buzzwords": sorted(shape_buzzwords),
                    "paired_bg_shape_id": None,
                })

        # 为属于纯装饰小字（kicker_badge / footer_slop / fake_metric）的独立文本框匹配背后的胶囊框或底栏色块
        for item in text_items:
            if len(item["paragraphs"]) == 1 and any(
                tag in item["issues"] for tag in ("kicker_badge", "footer_slop", "fake_metric")
            ):
                tb = tuple(item["bbox"])
                th = max(item["height"], 0.05)
                best_bg = None
                best_ioa = 0.0
                for bg in geom_candidates:
                    ioa = calc_ioa(tb, bg["bbox"])
                    # 背景框高度不能过大（防止误把整页背景或大卡片当作小胶囊框删掉）
                    if ioa >= 0.75 and bg["height"] <= max(th * 2.8, 1.25) and bg["height"] <= 1.35:
                        # 确保该背景框没有包含其他正常正文框
                        contains_other_text = False
                        for other in text_items:
                            if other["shape_id"] != item["shape_id"]:
                                if calc_ioa(tuple(other["bbox"]), bg["bbox"]) >= 0.5:
                                    contains_other_text = True
                                    break
                        if not contains_other_text and ioa > best_ioa:
                            best_ioa = ioa
                            best_bg = bg["shape_id"]
                if best_bg is not None:
                    item["paired_bg_shape_id"] = best_bg
                    report["summary"]["total_paired_bg_shapes"] += 1

            if item["issues"] or item["buzzwords"]:
                report["summary"]["total_flagged_shapes"] += 1
            report["summary"]["total_buzzword_hits"] += len(item["buzzwords"])

        report["slides"].append({
            "slide_index": idx,
            "text_shapes": text_items,
        })

    return report


def format_markdown_summary(report: dict) -> str:
    lines = [
        f"# PPTX AI 味扫描诊断报告：`{Path(report['file']).name}`",
        f"- 总页数：{report['slide_count']} 页 | 疑似病灶文本框：{report['summary']['total_flagged_shapes']} 个 | 配对胶囊/底栏色块：{report['summary']['total_paired_bg_shapes']} 个 | AI 黑话命中：{report['summary']['total_buzzword_hits']} 处\n",
    ]
    for slide in report["slides"]:
        lines.append(f"## 第 {slide['slide_index']} 页")
        for sp in slide["text_shapes"]:
            flags = sp["issues"] + ([f"黑话:{','.join(sp['buzzwords'])}"] if sp["buzzwords"] else [])
            flag_str = f" ⚠️ `{ ' | '.join(flags) }`" if flags else ""
            bg_str = f" (🔗 配对背景色块 `shape_id={sp['paired_bg_shape_id']}`)" if sp["paired_bg_shape_id"] else ""
            lines.append(f"- **Shape #{sp['shape_id']}** (`{sp['name']}`, top={sp['top_ratio']*100:.0f}%){flag_str}{bg_str}")
            for p in sp["paragraphs"]:
                p_flag = f" -> `{','.join(p['issues'])}`" if p["issues"] else ""
                lines.append(f"  - [P{p['paragraph_index']} | {p['font_pt']}pt] `{p['text']}`{p_flag}")
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Scan a PPTX file for AI-slop micro-copy, decorative badges, and buzzwords.")
    parser.add_argument("input_pptx", help="Path to the input .pptx file")
    parser.add_argument("--json", dest="json_out", help="Optional path to save structured JSON report")
    args = parser.parse_args()

    report = inspect_pptx(args.input_pptx)
    if args.json_out:
        Path(args.json_out).write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    sys.stdout.buffer.write(format_markdown_summary(report).encode("utf-8"))
    sys.stdout.buffer.write(b"\n")


if __name__ == "__main__":
    main()
