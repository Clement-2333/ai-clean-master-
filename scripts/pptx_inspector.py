"""
pptx_inspector.py — AI Clean Master PPTX 病灶扫描与配对背景框检测器

扫描 .pptx 文件，识别：
1. 顶部/卡片伪英文与八股眉题小字 (kicker_badge)
2. 卡片内同义反复的凑数解释小字 (redundant_subtext)
3. 页脚/底栏的假大空总结与免责废话 (footer_slop)
4. 伪造的装饰性微数据/角标与符号噪音 (fake_metric / emoji_slop)
5. 小字背后的配对装饰色块 (paired_bg_shape_id，如胶囊框、底栏横条)
6. 正文中的 AI 黑话与八股词条 (buzzwords)
7. 10 大行业自动分类与真实合规角标保护 (protected_footnote)
"""

