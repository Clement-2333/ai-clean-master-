    def test_apply_image_plan_skips_protected_regions_during_erasure(self, tmp_path):
        """
        Create a synthetic test image with distinct pixel patterns in each region.
        Apply a plan with fake slop regions, a redraw region, and protected footnote regions.
        Empirically verify that protected regions are skipped during erasure and their pixels are untouched.
        """
        # Create 800x600 image with distinct colored blocks
        img_w, img_h = 800, 600
        arr = np.full((img_h, img_w, 3), 245, dtype=np.uint8)

        # Region 1 (Fake badge): [50, 50, 200, 90] filled with red (255, 0, 0)
        arr[50:90, 50:200] = [255, 0, 0]

        # Region 2 (Fake slop): [50, 520, 750, 560] filled with blue (0, 0, 255)
        arr[520:560, 50:750] = [0, 0, 255]

        # Region 3 (Protected footnote with action=preserve, is_protected=True): [50, 420, 750, 450]
        # Filled with green (0, 200, 0)
        arr[420:450, 50:750] = [0, 200, 0]

        # Region 4 (Protected footnote via text matching): [50, 460, 750, 490]
        # Filled with purple (180, 0, 180)
        arr[460:490, 50:750] = [180, 0, 180]

        # Region 5 (Redraw region): [50, 150, 500, 220] filled with orange (255, 128, 0)
        arr[150:220, 50:500] = [255, 128, 0]

        in_img = tmp_path / "test_input_image.png"
        out_img = tmp_path / "test_cleaned_image.png"
        Image.fromarray(arr).save(str(in_img))

        plan = {
            "regions": [
                # Region 1: Fake pill badge -> erase
                {
                    "bbox": [50, 50, 200, 90],
                    "text": "SECTION 01 // AI-POWERED",
                    "action": "erase_only"
                },
                # Region 2: Fake slop footer -> erase
                {
                    "bbox": [50, 520, 750, 560],
                    "text": "注：以上数据仅供演示参考，Generated by AI",
                    "action": "erase_only"
                },
                # Region 3: Genuine clinical footnote explicitly marked preserve
                {
                    "bbox": [50, 420, 750, 450],
                    "text": "注：多中心双盲对照试验 (n=312, 95% CI 0.48-0.85, p < 0.01) 获 FDA 510(k) 准入",
                    "action": "preserve",
                    "is_protected": True
                },
                # Region 4: Genuine ISO footnote with action=erase_only but text triggers protection
                {
                    "bbox": [50, 460, 750, 490],
                    "text": "生产线全面符合 GB/T 1184-K 级公差与 ISO 13849-1 PLd 安全标准",
                    "action": "erase_only"
                },
                # Region 5: Redraw region
                {
                    "bbox": [50, 150, 500, 220],
                    "text": "核心诊断准确率提升至 98.6%",
                    "action": "erase_and_redraw",
                    "font_size": 24
                }
            ]
        }

        stats = imc.apply_image_plan(str(in_img), plan, str(out_img))

        assert stats["preserved_regions"] == 2, f"Expected 2 preserved regions, got {stats['preserved_regions']}"
        assert stats["erased_regions"] == 3, f"Expected 3 erased regions (1, 2, 5), got {stats['erased_regions']}"
        assert stats["redrawn_regions"] == 1, f"Expected 1 redrawn region (5), got {stats['redrawn_regions']}"

        # Verify pixel changes in saved image
        out_arr = np.array(Image.open(str(out_img)))

        # Region 1 (Red) should have been erased (no longer pure red)
        assert not np.all(out_arr[60:80, 60:190, :3] == [255, 0, 0]), "Region 1 (fake badge) was NOT erased!"

        # Region 2 (Blue) should have been erased (no longer pure blue)
        assert not np.all(out_arr[530:550, 60:740, :3] == [0, 0, 255]), "Region 2 (fake slop) was NOT erased!"

        # Region 3 (Green) MUST be preserved exactly: pixel values must remain [0, 200, 0]
        region3_pixels = out_arr[425:445, 60:740, :3]
        assert np.all(region3_pixels == [0, 200, 0]), (
            "CRITICAL: Region 3 (clinical footnote) was modified or erased!"
        )

        # Region 4 (Purple) MUST be preserved via domain protection: pixel values must remain [180, 0, 180]
        region4_pixels = out_arr[465:485, 60:740, :3]
        assert np.all(region4_pixels == [180, 0, 180]), (
            "CRITICAL: Region 4 (ISO engineering footnote) was modified or erased!"
        )

